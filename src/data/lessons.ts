export const lessons = worlds.flatMap((world) => world.lessons.map((lesson) => ({ ...lesson, worldId: world.id })))

export const lessonOrder = lessons.map((lesson) => lesson.id)

export function lessonById(id: string) {
  return lessons.find((lesson) => lesson.id === id) ?? null
}

export function worldOf(lessonId: string) {
  return worlds.find((world) => world.lessons.some((lesson) => lesson.id === lessonId)) ?? null
}

export function questionCorrectId(question: Question) {
  if (question.type === "myth") return question.correct
  return question.correctId
}
